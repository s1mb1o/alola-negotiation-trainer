export function translate(language: UiLanguage, key: string, fallback?: string): string {
  return dictionaries[language][key] ?? fallback ?? key
}

export function identifierLabel(language: UiLanguage, identifier: string, fallback?: string): string {
  const known = identifiers[language][identifier]
  if (known) return known
  // A participant identifier such as `participant_seller` is labelled by its role.
  const participantRole = /^participant_(.+)$/.exec(identifier)?.[1]
  if (participantRole && identifiers[language][participantRole]) return identifiers[language][participantRole]
  if (fallback !== undefined) return fallback
  if (!/^[a-z0-9_.-]+$/i.test(identifier)) return identifier
  return identifier
    .replace(/[._]/g, ' ')
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
}

export function apiErrorLabel(language: UiLanguage, code?: string): string | undefined {
  return code ? apiErrors[language][code] : undefined
}

export function actionLabel(language: UiLanguage, action?: string): string | undefined {
  if (!action) return undefined
  const normalized = action.toLowerCase()
  const keys: Record<string, string> = {
    inform: 'actionInform',
    message: 'actionInform',
    question: 'actionQuestion',
    offer: 'actionOffer',
    offer_set: 'actionOffer',
    counter_offer: 'actionCounterOffer',
    acceptance_intent: 'actionAccept',
    confirm_acceptance: 'actionAccept',
    accept: 'actionAccept',
    reject: 'actionReject',
    walk_away: 'actionWalkAway',
  }
  return translate(language, keys[normalized] ?? 'actionInform', action)
}
